create schema if not exists private;

-- sales_users ---------------------------------------------------------------

create table public.sales_users (
    id uuid primary key default gen_random_uuid(),
    name text,
    username text,
    role text,
    status text,
    created_at timestamptz not null default now(),
    "auth_user-id" uuid,
    email text,
    avatar_url text,
    photo_url text,
    constraint sales_users_role_check
        check (role = any (array['Admin', 'Sales', 'Digital Marketing', 'Secretary']))
);

-- leads (one row per lead/customer) -----------------------------------------

create table public.leads (
    id bigint generated by default as identity,
    customer_name text,
    phone text,
    business text,
    location text,
    status text,
    follow_up_date date,
    notes text,
    created_at timestamptz not null default now(),
    sales_id uuid references public.sales_users (id),
    appointment date,
    site_survey date,
    quotation date,
    closing date,
    created_by uuid,
    updated_by uuid,
    email text,
    status_started_at timestamptz,
    updated_at timestamptz default now(),
    lead_type text default 'Customer',
    constraint "sales-users_pkey" primary key (id),
    constraint leads_lead_type_check check (lead_type = any (array['Customer', 'Partner']))
);

-- customer_documents --------------------------------------------------------

create table public.customer_documents (
    id uuid primary key default gen_random_uuid(),
    customer_id bigint not null references public.leads (id) on delete cascade,
    document_type text not null default 'Other',
    file_name text not null,
    file_path text not null unique,
    file_size bigint,
    mime_type text not null,
    uploaded_by uuid not null references auth.users (id),
    uploaded_at timestamptz not null default now(),
    constraint customer_documents_type_check
        check (document_type = any (array['Quotation', 'Proposal', 'Company Profile', 'Other']))
);

create index idx_customer_documents_customer_id on public.customer_documents (customer_id);
create index idx_customer_documents_uploaded_by on public.customer_documents (uploaded_by);
create index idx_customer_documents_uploaded_at on public.customer_documents (uploaded_at desc);

-- functions -----------------------------------------------------------------

create or replace function public.set_leads_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create trigger leads_set_updated_at
    before update on public.leads
    for each row execute function public.set_leads_updated_at();

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path to 'public'
as $$
    select exists (
        select 1
        from public.sales_users
        where "auth_user-id" = auth.uid()
          and role = 'Admin'
    );
$$;

create or replace function public.get_login_email(p_username text)
returns text
language sql
security definer
set search_path to 'public'
as $$
    select email
    from public.sales_users
    where lower(username) = lower(p_username)
      and status = 'Active'
    limit 1;
$$;

create or replace function private.can_access_customer_document(p_customer_id bigint)
returns boolean
language sql
stable
security definer
set search_path to ''
as $$
    select
        exists (
            select 1
            from public.sales_users su
            where su."auth_user-id" = (select auth.uid())
              and lower(coalesce(su.role, '')) in ('admin', 'owner', 'administrator')
        )
        or exists (
            select 1
            from public.leads l
            inner join public.sales_users su on su.id = l.sales_id
            where l.id = p_customer_id
              and su."auth_user-id" = (select auth.uid())
        );
$$;

grant usage on schema private to authenticated;
grant execute on function private.can_access_customer_document(bigint) to authenticated;

-- Enables RLS on every new table created in public.
create or replace function public.rls_auto_enable()
returns event_trigger
language plpgsql
security definer
set search_path to 'pg_catalog'
as $$
declare
    cmd record;
begin
    for cmd in
        select *
        from pg_event_trigger_ddl_commands()
        where command_tag in ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
          and object_type in ('table', 'partitioned table')
    loop
        if cmd.schema_name is not null and cmd.schema_name in ('public') then
            begin
                execute format('alter table if exists %s enable row level security', cmd.object_identity);
            exception
                when others then
                    raise log 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
            end;
        end if;
    end loop;
end;
$$;

create event trigger ensure_rls
    on ddl_command_end
    when tag in ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
    execute function public.rls_auto_enable();

