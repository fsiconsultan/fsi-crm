create policy admin_read_sales_users on public.sales_users
    for select to authenticated using (is_admin());
create policy admin_insert_sales_users on public.sales_users
    for insert to authenticated with check (is_admin());
create policy admin_update_sales_users on public.sales_users
    for update to authenticated using (is_admin()) with check (is_admin());
create policy admin_delete_sales_users on public.sales_users
    for delete to authenticated using (is_admin());
create policy sales_read_own_profile on public.sales_users
    for select to authenticated using (auth.uid() = "auth_user-id");

create policy admin_read_all_leads on public.leads
    for select to authenticated using (is_admin());
create policy admin_insert_leads on public.leads
    for insert to authenticated with check (is_admin());
create policy admin_update_leads on public.leads
    for update to authenticated using (is_admin()) with check (is_admin());
create policy admin_delete_leads on public.leads
    for delete to authenticated using (is_admin());

create policy own_lead_read on public.leads
    for select to authenticated
    using (is_admin() or sales_id = (select su.id from sales_users su where su."auth_user-id" = auth.uid()));
create policy own_lead_insert on public.leads
    for insert to authenticated
    with check (is_admin() or sales_id = (select su.id from sales_users su where su."auth_user-id" = auth.uid()));
create policy own_lead_update on public.leads
    for update to authenticated
    using (is_admin() or sales_id = (select su.id from sales_users su where su."auth_user-id" = auth.uid()))
    with check (is_admin() or sales_id = (select su.id from sales_users su where su."auth_user-id" = auth.uid()));
create policy own_lead_delete on public.leads
    for delete to authenticated
    using (is_admin() or sales_id = (select su.id from sales_users su where su."auth_user-id" = auth.uid()));

create policy customer_documents_select on public.customer_documents
    for select to authenticated
    using (
        exists (
            select 1 from sales_users su
            where su."auth_user-id" = auth.uid()
              and lower(trim(both from su.role)) = any (array['admin', 'owner', 'administrator'])
        )
        or exists (
            select 1 from leads l join sales_users su on su.id = l.sales_id
            where l.id = customer_documents.customer_id and su."auth_user-id" = auth.uid()
        )
    );
create policy customer_documents_insert on public.customer_documents
    for insert to authenticated
    with check (
        uploaded_by = auth.uid()
        and (
            exists (
                select 1 from sales_users su
                where su."auth_user-id" = auth.uid()
                  and lower(trim(both from su.role)) = any (array['admin', 'owner', 'administrator'])
            )
            or exists (
                select 1 from leads l join sales_users su on su.id = l.sales_id
                where l.id = customer_documents.customer_id and su."auth_user-id" = auth.uid()
            )
        )
    );
create policy customer_documents_delete on public.customer_documents
    for delete to authenticated
    using (
        exists (
            select 1 from sales_users su
            where su."auth_user-id" = auth.uid()
              and lower(trim(both from su.role)) = any (array['admin', 'owner', 'administrator'])
        )
        or exists (
            select 1 from leads l join sales_users su on su.id = l.sales_id
            where l.id = customer_documents.customer_id and su."auth_user-id" = auth.uid()
